from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer
)

from reportlab.lib.styles import getSampleStyleSheet


def create_pdf(scan_data):

    pdf = SimpleDocTemplate(
        "scan_report.pdf"
    )

    styles = getSampleStyleSheet()

    elements = []

    # --------------------------------
    # Title
    # --------------------------------

    title = Paragraph(
        "Website Vulnerability Scan Report",
        styles['Title']
    )

    elements.append(title)

    elements.append(Spacer(1, 20))

    # --------------------------------
    # Website Information
    # --------------------------------

    website = Paragraph(
        f"<b>Target URL:</b> {scan_data['url']}",
        styles['BodyText']
    )

    scan_date = Paragraph(
        f"<b>Scan Date:</b> {scan_data['date']}",
        styles['BodyText']
    )

    elements.append(website)

    elements.append(scan_date)

    elements.append(Spacer(1, 20))

    # --------------------------------
    # Vulnerabilities
    # --------------------------------

    for vuln in scan_data['vulnerabilities']:

        vuln_name = Paragraph(
            f"<b>Vulnerability:</b> {vuln['name']}",
            styles['Heading2']
        )

        severity = Paragraph(
            f"<b>Severity:</b> {vuln['severity']}",
            styles['BodyText']
        )

        description = Paragraph(
            f"<b>Description:</b> {vuln['description']}",
            styles['BodyText']
        )

        solution = Paragraph(
            f"<b>Solution:</b> {vuln['solution']}",
            styles['BodyText']
        )

        elements.append(vuln_name)

        elements.append(severity)

        elements.append(description)

        elements.append(solution)

        elements.append(Spacer(1, 20))

    # --------------------------------
    # Footer
    # --------------------------------

    footer = Paragraph(
        "Generated by Website Vulnerability Scanner",
        styles['Italic']
    )

    elements.append(footer)

    pdf.build(elements)

    print("PDF report generated successfully!")
    return "scan_report.pdf"
    sample_data = {
    "url": "https://example.com",

    "date": "13 May 2026",

    "vulnerabilities": [

        {
            "name": "SQL Injection",
            "severity": "High",
            "description": "User input not sanitized.",
            "solution": "Use parameterized queries."
        },

        {
            "name": "Cross Site Scripting",
            "severity": "Medium",
            "description": "Scripts can be injected.",
            "solution": "Validate user inputs."
        }
    ]
}
