from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer
)

from reportlab.lib.styles import getSampleStyleSheet


def create_pdf():

    # Create PDF file
    pdf = SimpleDocTemplate(
        "scan_report.pdf"
    )

    # Default styles
    styles = getSampleStyleSheet()

    # Content list
    elements = []

    # --------------------------------
    # Title
    # --------------------------------

    title = Paragraph(
        "Website Vulnerability Scan Report",
        styles['Title']
    )

    elements.append(title)

    elements.append(Spacer(1, 20))

    # --------------------------------
    # Website Information
    # --------------------------------

    website = Paragraph(
        "<b>Target URL:</b> https://example.com",
        styles['BodyText']
    )

    scan_date = Paragraph(
        "<b>Scan Date:</b> 13 May 2026",
        styles['BodyText']
    )

    elements.append(website)

    elements.append(scan_date)

    elements.append(Spacer(1, 20))

    # --------------------------------
    # Vulnerability 1
    # --------------------------------

    vuln1 = Paragraph(
        "<b>Vulnerability:</b> SQL Injection",
        styles['Heading2']
    )

    severity1 = Paragraph(
        "<b>Severity:</b> High",
        styles['BodyText']
    )

    description1 = Paragraph(
        "<b>Description:</b> User input is not sanitized properly.",
        styles['BodyText']
    )

    solution1 = Paragraph(
        "<b>Solution:</b> Use parameterized queries.",
        styles['BodyText']
    )

    elements.append(vuln1)

    elements.append(severity1)

    elements.append(description1)

    elements.append(solution1)

    elements.append(Spacer(1, 20))

    # --------------------------------
    # Vulnerability 2
    # --------------------------------

    vuln2 = Paragraph(
        "<b>Vulnerability:</b> Cross Site Scripting (XSS)",
        styles['Heading2']
    )

    severity2 = Paragraph(
        "<b>Severity:</b> Medium",
        styles['BodyText']
    )

    description2 = Paragraph(
        "<b>Description:</b> Malicious scripts can be injected.",
        styles['BodyText']
    )

    solution2 = Paragraph(
        "<b>Solution:</b> Validate and sanitize inputs.",
        styles['BodyText']
    )

    elements.append(vuln2)

    elements.append(severity2)

    elements.append(description2)

    elements.append(solution2)

    elements.append(Spacer(1, 20))

    # --------------------------------
    # Footer
    # --------------------------------

    footer = Paragraph(
        "Generated by Website Vulnerability Scanner",
        styles['Italic']
    )

    elements.append(footer)

    # Create PDF
    pdf.build(elements)

    print("PDF report generated successfully!")


# Run Function
create_pdf()